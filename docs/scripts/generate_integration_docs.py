# ruff: noqa: INP001
"""Generate Jira and GitHub component-parameter partials from bundle code.

The partials are the field tables on the bundle pages. Component classes supply
the inputs and outputs. ``capabilities.v1.json`` supplies scopes and deployment
contexts. Re-run this script after either source changes. Do not edit the
partials by hand.

    uv run python docs/scripts/generate_integration_docs.py
    uv run python docs/scripts/generate_integration_docs.py --check
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
PARTIAL_DIR = REPO_ROOT / "docs" / "docs"

CONTEXT_LABELS = {
    "hosted": "hosted Langflow",
    "self_managed": "self-managed Langflow",
    "desktop": "Langflow Desktop",
    "headless": "headless Langflow",
}


@dataclass(frozen=True)
class BundleSpec:
    """One integration whose parameter partial is generated."""

    package: str
    module: str
    manifest: Path

    @property
    def output_path(self) -> Path:
        """Markdown partial imported by the bundle page."""
        return PARTIAL_DIR / f"_partial-bundle-{self.package}-parameters.mdx"


BUNDLES = (
    BundleSpec(
        package="github",
        module="lfx_github.components.github",
        manifest=REPO_ROOT / "src/bundles/github/src/lfx_github/components/github/capabilities.v1.json",
    ),
    BundleSpec(
        package="jira",
        module="lfx_jira.components.jira",
        manifest=REPO_ROOT / "src/bundles/jira/src/lfx_jira/components/jira/capabilities.v1.json",
    ),
)


def _prepare_import_path() -> None:
    """Import the workspace copies of lfx and the two bundles."""
    entries = (
        REPO_ROOT / "src" / "lfx" / "src",
        REPO_ROOT / "src" / "bundles" / "github" / "src",
        REPO_ROOT / "src" / "bundles" / "jira" / "src",
    )
    for entry in reversed(entries):
        text = str(entry)
        if text in sys.path:
            sys.path.remove(text)
        sys.path.insert(0, text)


def _mdx(value: object) -> str:
    """Escape text for an MDX table cell."""
    text = "" if value is None else str(value)
    text = " ".join(text.split())
    return text.replace("|", "\\|").replace("<", "&lt;").replace("{", "&#123;").replace("}", "&#125;")


def _join(items: list[str]) -> str:
    pair = 2
    if len(items) == 1:
        return items[0]
    if len(items) == pair:
        return f"{items[0]} and {items[1]}"
    return ", ".join(items[:-1]) + f", and {items[-1]}"


def _input_description(field: Any) -> str:
    parts: list[str] = []
    if getattr(field, "advanced", False):
        parts.append("Advanced.")
    info = getattr(field, "info", None)
    if isinstance(info, str) and info.strip():
        parts.append(info.strip())
    options = getattr(field, "options", None)
    if isinstance(options, list) and options:
        rendered = ", ".join(f"`{option}`" for option in options)
        parts.append(f"Options: {rendered}.")
    return " ".join(parts)


def _component_classes(module_name: str) -> dict[str, type]:
    _prepare_import_path()
    from lfx.custom.custom_component.component import Component

    module = importlib.import_module(module_name)
    classes: dict[str, type] = {}
    for name in getattr(module, "__all__", ()):
        obj = getattr(module, name)
        if inspect.isclass(obj) and issubclass(obj, Component):
            classes[obj.__name__] = obj
    return classes


def _capabilities(manifest_path: Path) -> list[dict[str, Any]]:
    payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    capabilities = payload.get("capabilities")
    if not isinstance(capabilities, list):
        message = f"{manifest_path} has no capabilities list"
        raise TypeError(message)
    return capabilities


def render_partial(spec: BundleSpec) -> str:
    """Render the parameter partial for one bundle."""
    classes = _component_classes(spec.module)
    capabilities = _capabilities(spec.manifest)
    referenced = [item["component_ref"] for item in capabilities]
    missing = [name for name in referenced if name not in classes]
    extra = sorted(set(classes) - set(referenced))
    if missing or extra:
        message = f"{spec.package} component refs do not match {spec.module}: missing={missing} extra={extra}"
        raise ValueError(message)

    lines = [
        "{/* Generated by docs/scripts/generate_integration_docs.py. Do not edit. */}",
        "",
        "## Component parameters",
        "",
        "Field names and descriptions match the components in this release.",
        "",
    ]
    for capability in capabilities:
        component = classes[capability["component_ref"]]
        lines.extend(_render_component(component, capability))
    return "\n".join(lines).rstrip() + "\n"


def _render_component(component: type, capability: dict[str, Any]) -> list[str]:
    description = getattr(component, "description", "") or ""
    lines = [f"### {component.display_name}", ""]
    if description:
        lines.extend([description, ""])
    contexts = [_mdx(CONTEXT_LABELS.get(name, name)) for name in capability.get("deployment_contexts", [])]
    if contexts:
        lines.extend([f"Runs in {_join(contexts)}.", ""])
    scopes = [str(scope) for scope in capability.get("required_scopes", [])]
    if scopes:
        rendered = ", ".join(f"`{_mdx(scope)}`" for scope in scopes)
        lines.extend([f"**Required scopes:** {rendered}", ""])
    input_headers = ("Name", "Display name", "Type", "Required", "Description")
    lines.extend(_render_table("Inputs", _input_rows(component), input_headers))
    lines.extend(_render_table("Outputs", _output_rows(component), ("Name", "Display name")))
    return lines


def _input_rows(component: type) -> list[tuple[str, ...]]:
    rows: list[tuple[str, ...]] = []
    for field in getattr(component, "inputs", []):
        name = getattr(field, "name", "")
        if not isinstance(name, str) or not name or name.startswith("_"):
            continue
        if getattr(field, "show", True) is False:
            continue
        required = "yes" if getattr(field, "required", False) else "no"
        rows.append(
            (
                f"`{_mdx(name)}`",
                _mdx(getattr(field, "display_name", name)),
                _mdx(type(field).__name__),
                required,
                _mdx(_input_description(field)),
            )
        )
    return rows


def _output_rows(component: type) -> list[tuple[str, ...]]:
    rows: list[tuple[str, ...]] = []
    for output in getattr(component, "outputs", []):
        name = getattr(output, "name", "")
        if not isinstance(name, str) or not name:
            continue
        rows.append((f"`{_mdx(name)}`", _mdx(getattr(output, "display_name", name))))
    return rows


def _render_table(title: str, rows: list[tuple[str, ...]], headers: tuple[str, ...]) -> list[str]:
    lines = [f"#### {title}", ""]
    if not rows:
        return [*lines, "None.", ""]
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("| " + " | ".join("---" for _ in headers) + " |")
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    lines.append("")
    return lines


def write_partials(*, check: bool) -> list[str]:
    """Write every partial, or return the paths that differ when checking."""
    drifted: list[str] = []
    for spec in BUNDLES:
        rendered = render_partial(spec)
        current = spec.output_path.read_text(encoding="utf-8") if spec.output_path.exists() else ""
        if current == rendered:
            continue
        if check:
            drifted.append(str(spec.output_path.relative_to(REPO_ROOT)))
            continue
        spec.output_path.write_text(rendered, encoding="utf-8")
    return drifted


def main(argv: list[str] | None = None) -> int:
    """Generate the partials, or fail when ``--check`` finds drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when a partial differs from the components")
    args = parser.parse_args(argv)
    drifted = write_partials(check=args.check)
    if drifted:
        sys.stderr.write("Integration parameter partials are out of date:\n")
        sys.stderr.write("\n".join(f"  {path}" for path in drifted) + "\n")
        sys.stderr.write("Run: uv run python docs/scripts/generate_integration_docs.py\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
